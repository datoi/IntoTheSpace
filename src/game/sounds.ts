/**
 * Tiny imperative sound board. Each effect gets its own player so rapid
 * retriggers just seek back to 0.
 *
 * The board is organised by WHAT AN EVENT MEANS, not by what plays it:
 *   • pop1..pop5 — the kill-pitch ladder, pre-pitched, read by playKill.
 *   • shot_*     — what the player did.
 *   • pickup_*   — what the player got. Always rises.
 *   • sys_*      — what the game is reporting about state.
 *   • ui_*       — what the SHELL is saying back to a finger. The only board
 *                  that plays outside a run, and the only one carried on the
 *                  `ui` mixer channel.
 *
 * The pops are the one family still using pre-pitched samples; the newer
 * boards use one sample transposed at playback (see playPitched), so adding a
 * member costs no asset. Coin and heart used to borrow pop2 and pop4, which
 * meant a pickup was indistinguishable from a x3 kill — the ladder is a
 * readout, and nothing else may speak with its voice.
 */
